/** The DoDAF generator: creates or reuses diagrams, requests images, writes tables and the document (D80, D82, D83). No `vscode` import. */
import type { Element, ModelIndex } from "../model/index.js";
import { createDiagram } from "../diagram/create.js";
import { ToolError, type DiagramService, type DodafFiles } from "../agent-tools/types.js";
import { encodeLink, writeDocument, type DocumentSection } from "./document.js";
import { selectByMetadata } from "./library.js";
import { VIEWS } from "./mapping.js";
import { planViews, type ViewPlan } from "./plan.js";
import { escapeMd, renderMarkdown, type Gap, type Table } from "./render.js";
import { annotated, attributeValue, doc } from "./tables/common.js";
import { buildAv1, buildAv2, buildCv1, buildDiv2, buildOv4, buildOv5a, buildStdV1, buildSv5a } from "./tables/index.js";
import type { ViewId } from "./mapping.js";

export const DEFAULT_FOLDER = "docs/dodaf";
export const IMAGE_EXTENSIONS = ["png", "svg", "jpg", "jpeg", "gif"];

const BUILDERS: Partial<Record<ViewId, (ix: ModelIndex, root: Element) => Table>> = {
  "AV-1": buildAv1, "AV-2": buildAv2, "CV-1": buildCv1, "OV-4": buildOv4, "OV-5a": buildOv5a, "SV-5a": buildSv5a, "StdV-1": buildStdV1, "DIV-2": buildDiv2,
};

export interface GenerateRequest {
  index: ModelIndex;
  root: Element;
  /** Workspace-relative folder, already validated. */
  folder: string;
  views?: readonly string[];
  imageFormat: "svg" | "png";
  /** Plan only: nothing is created or written. */
  plan: boolean;
  /** Replace a document or images this generator did not write. */
  overwrite?: boolean;
  /** Workspace-relative path of a document URI; undefined outside the workspace. */
  uriToPath(uri: string): string | undefined;
  files: DodafFiles;
  /** Absent when diagrams are not available (diagram sections are skipped). */
  diagrams?: DiagramService;
}

export interface ViewReport {
  id: ViewId;
  form: string;
  status: "written" | "empty" | "skipped" | "planned";
  diagram?: string;
  diagramCreated?: boolean;
  image?: string;
  note?: string;
}

export interface GenerateReport {
  document: string;
  planOnly: boolean;
  views: ViewReport[];
  gaps: Gap[];
  /** Metadata definitions no element uses, per view (D79). */
  missing: Record<string, string[]>;
  /** Existing files this generator did not write; only replaced with `overwrite: true`. */
  overwriteRefused?: string[];
}

export const GENERATED_MARKER = "<!-- generated by sysml_dodaf_generate -->";

const dirname = (p: string) => (p.includes("/") ? p.slice(0, p.lastIndexOf("/")) : "");
const join = (...parts: string[]) => parts.filter((p) => p !== "").join("/");

/** Why `folder` is not an acceptable workspace-relative path, or undefined. */
export function validateFolder(folder: string): string | undefined {
  if (!folder.trim()) return "path is empty";
  if (folder.includes("\0")) return "path contains a NUL character";
  if (folder.includes("\\")) return "path must use forward slashes";
  if (folder.startsWith("/") || /^[A-Za-z]:/.test(folder)) return "path must be relative to the workspace root";
  if (folder.split("/").some((s) => s === ".." || s === "." || s === "")) return "path must not contain empty, . or .. segments";
  return undefined;
}

/** The author's OV-1 picture (`@OV1Graphic { path }`) under `root`, when it names an image file. */
function ov1Graphic(index: ModelIndex, root: Element): { path?: string; problem?: string } {
  for (const el of annotated(index, root, "OV1Graphic")) {
    const p = attributeValue(index, el, "path");
    if (!p) continue;
    const bad = validateFolder(p);
    if (bad) return { problem: `@OV1Graphic path "${p.slice(0, 80)}": ${bad}` };
    if (!IMAGE_EXTENSIONS.includes((p.split(".").pop() ?? "").toLowerCase())) return { problem: `@OV1Graphic path "${p.slice(0, 80)}" is not a png, svg, jpg or gif file` };
    return { path: p };
  }
  return {};
}

async function diagramFor(req: GenerateRequest, p: ViewPlan, existing: Set<string>): Promise<{ path: string; created: boolean } | { skip: string }> {
  const svc = req.diagrams;
  if (!svc) return { skip: "the diagram view is not available" };
  const rootEl = req.index.findByQualifiedName(p.root)[0];
  const srcPath = rootEl ? req.uriToPath(rootEl.uri) : undefined;
  if (!rootEl || srcPath === undefined || !p.fileName || !p.diagramKind) return { skip: "the root has no source file in the workspace" };
  const path = join(dirname(srcPath), p.fileName);
  if (existing.has(path)) return { path, created: false };
  if (req.plan) return { path, created: true };
  const kind = p.diagramKind;
  // A package root cannot head an interconnection, action or sequence view: try the annotated elements under it.
  const within = (e: Element) => e.qualifiedName !== undefined && e.qualifiedName.startsWith(`${p.root}::`);
  const picks = (VIEWS.find((v) => v.id === p.id)?.selects ?? []).flatMap((d) => selectByMetadata(req.index, d).filter(within));
  const candidates = [rootEl, ...picks].slice(0, 20);
  let last = "";
  for (const c of candidates) {
    try {
      const r = await svc.create({ path, root: c, make: (sourceOf) => createDiagram(req.index, c.qualifiedName!, kind, { sourceOf }) });
      return { path: r.path, created: true };
    } catch (e) {
      if (last === "") last = e instanceof Error ? e.message : String(e);
    }
  }
  return { skip: `diagram not created: ${last}` };
}

interface PendingImage {
  path: string;
  text?: string;
  bytes?: Uint8Array;
  /** Workspace-relative source of an author-supplied graphic. */
  from?: string;
  section: DocumentSection;
}

/** Runs the plan. Existing `.sysmld` files are never rewritten; Markdown and images may be overwritten. */
export async function generateDocument(req: GenerateRequest): Promise<GenerateReport> {
  const plans = planViews(req.index, req.root, req.views);
  const baseName = (req.root.name ?? "Architecture").replace(/[^\w.-]+/g, "_");
  const docPath = join(req.folder, `${baseName}.md`);
  const existing = new Set((req.diagrams ? await req.diagrams.list() : []).map((d) => d.path));
  const sections: DocumentSection[] = [];
  const views: ViewReport[] = [];
  const gaps: Gap[] = [];
  const missing: Record<string, string[]> = {};
  const pending: PendingImage[] = [];

  for (const p of plans) {
    if (p.missing.length) missing[p.id] = [...new Set([...(missing[p.id] ?? []), ...p.missing])];
    const report: ViewReport = { id: p.id, form: p.form, status: p.empty ? "empty" : "written" };
    const prior = p.id === "OV-5b" ? sections.find((s) => s.id === "OV-5b") : undefined;
    const section: DocumentSection = prior ?? { id: p.id };
    const builder = BUILDERS[p.id];
    if (builder) {
      const t = builder(req.index, req.root);
      gaps.push(...t.gaps);
      if (!p.empty) section.markdown = renderMarkdown(t);
    }
    if (p.id === "OV-1") {
      const n = doc(req.root);
      if (n) section.narrative = escapeMd(n);
    }
    if (p.form === "diagram" && !p.empty) {
      const prefix = `${baseName}-${p.id}`;
      const stem = (p.fileName ?? prefix).replace(/\.sysmld$/, "");
      const rel = `images/${p.id}${stem.slice(prefix.length)}`;
      const link = (r: string) => (p.id === "OV-5b" ? (section.markdown = [section.markdown, `![OV-5b](${encodeLink(r)})`].filter(Boolean).join("\n\n")) : (section.image = r));
      const g = p.id === "OV-1" ? ov1Graphic(req.index, req.root) : {};
      if ("problem" in g && g.problem) gaps.push({ view: "OV-1", message: g.problem });
      if ("path" in g && g.path) {
        const target = `${rel}.${g.path.split(".").pop()!.toLowerCase()}`;
        report.image = join(req.folder, target);
        report.note = "author-supplied graphic copied";
        if (!req.plan) pending.push({ path: report.image, from: g.path, section });
        link(target);
      } else {
        const d = await diagramFor(req, p, existing);
        if ("skip" in d) {
          section.skipped = d.skip;
          report.status = "skipped";
          report.note = d.skip;
        } else {
          report.diagram = d.path;
          report.diagramCreated = d.created;
          existing.add(d.path);
          if (!req.plan) {
            const img = await req.diagrams!.renderImage(d.path, req.imageFormat);
            if (!img.ok) {
              // The tables are still written; the diagram view could not draw (D83).
              report.note = `image not exported: ${img.reason}`;
              const text = `_Image not exported: ${escapeMd(img.reason)}_`;
              section.narrative = [section.narrative, text].filter(Boolean).join("\n\n");
            } else {
              const target = `${rel}.${req.imageFormat}`;
              report.image = join(req.folder, target);
              pending.push(img.svg !== undefined ? { path: report.image, text: img.svg, section } : { path: report.image, bytes: img.png, section });
              link(target);
            }
          }
        }
      }
    }
    if (req.plan && report.status === "written") report.status = "planned";
    views.push(report);
    if (!prior) sections.push(section);
  }

  // Files the generator did not write are never replaced unless asked (the marker identifies its own document).
  const refused: string[] = [];
  const docExists = await req.files.exists(docPath);
  const ours = docExists && new TextDecoder().decode((await req.files.readBytes(docPath).catch(() => new Uint8Array())).slice(0, 200)).includes(GENERATED_MARKER);
  if (docExists && !ours) refused.push(docPath);
  const targets = req.plan ? views.flatMap((v) => (v.image ? [v.image] : [])) : pending.map((i) => i.path);
  for (const t of targets) if (!ours && (await req.files.exists(t))) refused.push(t);
  if (refused.length && !req.overwrite) {
    if (req.plan) return { document: docPath, planOnly: true, views, gaps, missing, overwriteRefused: refused };
    throw new ToolError(`Not generated: ${refused.slice(0, 5).join(", ")} already exist and were not written by sysml_dodaf_generate. Choose another folder, or pass overwrite: true to replace them.`);
  }

  if (!req.plan) {
    for (const im of pending) {
      if (im.from) {
        const bytes = await req.files.readBytes(im.from).catch(() => undefined);
        if (!bytes) {
          // No link to a file that was not written.
          delete im.section.image;
          im.section.skipped = `graphic ${im.from} could not be read`;
          continue;
        }
        await req.files.writeBytes(im.path, bytes);
      } else if (im.text !== undefined) await req.files.writeText(im.path, im.text);
      else await req.files.writeBytes(im.path, im.bytes!);
    }
    await req.files.writeText(docPath, GENERATED_MARKER + "\n" + writeDocument(`${req.root.name ?? "Architecture"} DoDAF Architecture Description`, sections));
  }
  return { document: docPath, planOnly: req.plan, views, gaps, missing };
}
